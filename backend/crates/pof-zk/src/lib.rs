//! Drives the delegation circuit (vendored, with the Vouch threshold modification) to prove
//! and verify `HoldsAtLeast` claims.
//!
//! The envelope is bound into the proof by the holder's spend-authorisation signature: the
//! key the circuit proves controls the notes (`rk`) signs the statement and every public input,
//! which a viewing-key holder cannot do. The circuit's `vote_round_id` (and from it the nullifier
//! domain and the five tags) is, in version 1, the statement hash — a second binding; in version
//! 2 it is the scope (circuit, audience, epoch), so the same note gives the same tag inside one
//! scope and reuse becomes visible to that verifier.
//!
//! Carried public inputs, in order (9 × 32 bytes):
//! `nf_signed, rk, cmx_new, van_comm, gov_null_1..5`. Everything else — `vote_round_id`,
//! `dom`, `nc_root`, `nf_imt_root`, `min_ballots` — the verifier derives itself.
//! Circuit 2 (exit certificates) carries six more: `reveal` and `revealed_nf_1..5`, the real
//! nullifiers of the proven notes (zero when `reveal` is 0).

